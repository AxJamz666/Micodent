const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async ({page,context,origin,root,mode}) => {
  await page.goto(`${origin}/finanzas`);
  await page.getByRole('button',{name:'Configurar recargo POS',exact:true}).click();
  const settings=page.getByRole('dialog',{name:'Recargo por tarjeta (POS)'});
  await settings.getByRole('spinbutton').fill('5.5');
  const configSaved=page.waitForResponse(r=>r.url().endsWith('/dashboard/configuracion-pos')&&r.request().method()==='PUT');
  await settings.getByRole('button',{name:'Guardar porcentaje'}).click();assert.equal((await configSaved).status(),200);
  await settings.waitFor({state:'detached'});
  assert.equal(await page.locator('[data-financial-kpi="Total Cobrado"]').count(),0);
  assert.equal(await page.locator('[data-financial-kpi="Gastos Operativos"]').count(),0);
  const observer=await context.newPage();
  const errors=[];observer.on('pageerror',e=>errors.push(e.message));
  try {
    await observer.goto(origin+'/');
    await observer.locator('[data-patient-debt="1"]').waitFor();
    assert(await observer.locator('[data-patient-debt]').count()>10);
    assert(await observer.locator('[data-patient-debt="1"] [data-pending-treatment]').count()>2);
    await page.goto(`${origin}/pacientes/1?tab=evolucion`);
    await page.getByRole('button',{name:'Nuevo Tratamiento',exact:true}).click();
    const modal=page.locator('.dialog-overlay');
    const description=`POS inicial ${mode}`;
    await modal.locator('textarea').nth(0).fill(description);
    await modal.locator('textarea').nth(1).fill('Control sintetico');
    await modal.locator('input[placeholder="0.00"]').last().fill('380');
    await modal.getByPlaceholder('0.00 (opcional)',{exact:true}).fill('100');
    await modal.getByRole('button',{name:'Tarjeta (POS)',exact:true}).click();
    await modal.locator('[data-pos-preview]').filter({hasText:'105.50'}).waitFor();
    await modal.locator('[data-pos-preview]').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(root,`${mode}-pos-inicial.png`)});
    const created=page.waitForResponse(r=>/\/historias\/\d+\/consultas$/.test(r.url())&&r.request().method()==='POST');
    await modal.getByRole('button',{name:'Guardar y Firmar',exact:true}).click();
    const response=await created;assert.equal(response.status(),201);
    const id=(await response.json()).consultaId;
    await modal.waitFor({state:'detached'});
    const debt=observer.locator(`[data-pending-treatment="${id}"]`);
    await debt.waitFor();assert((await debt.innerText()).includes('280.00'));
    await observer.locator('[data-patient-debt="1"]').scrollIntoViewIfNeeded();
    await observer.screenshot({path:path.join(root,`${mode}-pendientes.png`)});
    await page.getByRole('row').filter({hasText:description}).getByRole('button',{name:'Abonar',exact:true}).click();
    await modal.getByPlaceholder('0.00',{exact:true}).fill('280');
    await modal.getByRole('button',{name:'Tarjeta (POS)',exact:true}).click();
    await modal.locator('[data-pos-preview]').filter({hasText:'295.40'}).waitFor();
    const paid=page.waitForResponse(r=>r.url().includes('/pagos')&&r.request().method()==='POST');
    await modal.getByRole('button',{name:'Confirmar Abono',exact:true}).click();assert.equal((await paid).status(),201);
    await debt.waitFor({state:'detached'});
    await observer.setViewportSize({width:390,height:844});
    await observer.locator('[data-patient-debt="1"]').scrollIntoViewIfNeeded();
    await observer.locator('[data-patient-debt="1"]').evaluate(el=>{el.parentElement.parentElement.scrollTop=0;});
    await observer.screenshot({path:path.join(root,`${mode}-pendientes-mobile.png`)});
    assert(await observer.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    assert.deepEqual(errors,[]);
  } finally {await observer.close();}
  await page.goto(`${origin}/finanzas`);
  await page.getByRole('button',{name:'Configurar recargo POS',exact:true}).click();
  await settings.getByRole('spinbutton').fill('4');
  await settings.getByRole('button',{name:'Guardar porcentaje'}).click();await settings.waitFor({state:'detached'});
};
